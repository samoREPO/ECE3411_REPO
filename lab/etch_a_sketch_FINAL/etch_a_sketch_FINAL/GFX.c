/* --------------------------------------------------------------------------
 * Temporary cursor overlay
 * --------------------------------------------------------------------------
 * The cursor is not part of the drawing. It is an overlay drawn into the
 * framebuffer, so we save the pixel underneath it before turning it on and
 * restore that pixel when turning it off.
 */

typedef struct
{
	bool visible;
	uint8_t x;
	uint8_t y;
	uint8_t saved_pixel;
	uint16_t tick_count;
} gfx_cursor_t;

static gfx_cursor_t gfx_cursor = {0};

static void gfx_cursor_restore_pixel(void)
{
	if (!gfx_cursor.visible)
	{
		return;
	}

	if (gfx_cursor.saved_pixel)
	{
		SH1106_SetPixel(gfx_cursor.x, gfx_cursor.y);
	}
	else
	{
		SH1106_ClearPixel(gfx_cursor.x, gfx_cursor.y);
	}

	gfx_cursor.visible = false;
}

static void gfx_cursor_draw_overlay(uint8_t x, uint8_t y)
{
	gfx_cursor.x = x;
	gfx_cursor.y = y;
	gfx_cursor.saved_pixel = SH1106_GetPixel(x, y);
	gfx_cursor.visible = true;

	SH1106_SetPixel(x, y);
}

void gfx_cursor_hide(void)
{
	gfx_cursor_restore_pixel();
	gfx_cursor.tick_count = 0;
}

void gfx_cursor_blink(uint8_t x, uint8_t y, uint16_t blink_period_ticks)
{
	if (blink_period_ticks == 0)
	{
		blink_period_ticks = 1;
	}

	/* If the cursor moved while visible, restore the old location first. */
	if (gfx_cursor.visible && (gfx_cursor.x != x || gfx_cursor.y != y))
	{
		gfx_cursor_restore_pixel();
	}

	gfx_cursor.tick_count++;

	if (gfx_cursor.tick_count < blink_period_ticks)
	{
		return;
	}

	gfx_cursor.tick_count = 0;

	if (gfx_cursor.visible)
	{
		gfx_cursor_restore_pixel();
	}
	else
	{
		gfx_cursor_draw_overlay(x, y);
	}
}

/* Breshenham's Line Drawing Alogrithm*/
//using slope intercept form of a line we will fill in pixels
// This algorithm uses integers
void draw_line(int16_t x0, int16_t y0, int16_t x1, int16_t y1)
{
	// define change in x and y
	int16_t dx = abs(x1 - x0);
	int16_t dy = abs(y1 - y0);

	// define direction of change
	int16_t sx = (x0 < x1) ? 1 : -1;
	int16_t sy = (y0 < y1) ? 1 : -1;

	int16_t err = dx - dy;
	
	while(1)
	{
		// always draw a pixel if in the bound of the screen
		if(x0 < SH1106_WIDTH && y0 < SH1106_HEIGHT)
		{
			SH1106_SetPixel(x0, y0);
		}
		
		// if endpoint connected, break
		if(x0 == x1 && y0 == y1)
		{
			break;
		}
		
		int16_t e2 = 2 * err;
		
		if(e2 > -dy)
		{
			err-=dy;
			x0 += sx;
		}
		
		if(e2 < dx)
		{
			err += dx;
			y0 += sy;
		}
	}
}



static const uint8_t *get_char_bitmap(char c)
{
	if (c < FONT5X7_FIRST || c > FONT5X7_LAST)
	{
		c = '?';
	}

	return font5x7[c - FONT5X7_FIRST];
}

void draw_char(uint8_t x, uint8_t y, char c)
{
	const uint8_t *bitmap = get_char_bitmap(c);

	for (uint8_t col = 0; col < FONT5X7_WIDTH; col++)
	{
		uint8_t column_data = bitmap[col];

		for (uint8_t row = 0; row < FONT5X7_HEIGHT; row++)
		{
			if (column_data & (1 << row))
			{
				SH1106_SetPixel(x + col, y + row);
			}
			else
			{
				SH1106_ClearPixel(x + col, y + row);
			}
		}
	}

	/* clear the 1-pixel spacing column after the character */
	for (uint8_t row = 0; row < FONT5X7_HEIGHT; row++)
	{
		SH1106_ClearPixel(x + FONT5X7_WIDTH, y + row);
	}
}

void draw_string(uint8_t x, uint8_t y, const char *str)
{
	uint8_t cursor_x = x;
	uint8_t cursor_y = y;

	while (*str != '\0')
	{
		if (*str == '\n')
		{
			cursor_x = x;
			cursor_y += FONT5X7_HEIGHT + 1;
			str++;
			continue;
		}

		if (cursor_x + FONT5X7_WIDTH >= SH1106_WIDTH)
		{
			cursor_x = x;
			cursor_y += FONT5X7_HEIGHT + 1;
		}

		if (cursor_y + FONT5X7_HEIGHT >= SH1106_HEIGHT)
		{
			break;
		}

		draw_char(cursor_x, cursor_y, *str);

		cursor_x += FONT5X7_WIDTH + FONT5X7_SPACING;
		str++;
	}
}